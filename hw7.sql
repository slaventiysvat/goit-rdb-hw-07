USE northwind;

-- ============================================================
-- Завдання 1
-- Витягти рік, місяць і число з атрибута date таблиці orders
-- Вивести: id, date, year, month, day
-- ============================================================

SELECT
    id,
    date,
    YEAR(date)  AS year,
    MONTH(date) AS month,
    DAY(date)   AS day
FROM orders;

-- ============================================================
-- Завдання 2
-- Додати один день до атрибута date таблиці orders
-- Вивести: id, date, date + 1 день
-- ============================================================

SELECT
    id,
    date,
    DATE_ADD(date, INTERVAL 1 DAY) AS date_plus_one
FROM orders;

-- ============================================================
-- Завдання 3
-- Відобразити кількість секунд з початку відліку (UNIX timestamp)
-- для атрибута date таблиці orders
-- Вивести: id, date, unix_timestamp
-- ============================================================

SELECT
    id,
    date,
    UNIX_TIMESTAMP(date) AS unix_timestamp
FROM orders;

-- ============================================================
-- Завдання 4
-- Порахувати кількість рядків у orders, де date
-- між '1996-07-10 00:00:00' та '1996-10-08 00:00:00'
-- ============================================================

SELECT COUNT(*) AS orders_count
FROM orders
WHERE date BETWEEN '1996-07-10 00:00:00' AND '1996-10-08 00:00:00';

-- ============================================================
-- Завдання 5
-- Вивести id, date та JSON-об'єкт {"id": <id>, "date": <date>}
-- для таблиці orders
-- ============================================================

SELECT
    id,
    date,
    JSON_OBJECT('id', id, 'date', date) AS json_object
FROM orders;
